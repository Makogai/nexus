// Generate THIRD_PARTY_NOTICES.md: every third-party component that ships in NEXUS (Rust crates linked into the
// desktop app and the CLI, npm packages bundled into the frontend) with its licence and licence text (ADR-0035).
// Build-time and development-only dependencies are not distributed and are left out.
//
//   node scripts/third-party-notices.mjs            (from the repository root; needs cargo and apps/desktop/node_modules)
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const repo = join(dirname(fileURLToPath(import.meta.url)), '..')
const LICENSE_FILE = /^(licen[cs]e|copying|notice)([-._].*)?$/i
const components = [] // { ecosystem, name, version, license, repository, texts: [{file, text}] }

function licenceTexts(dir) {
  if (!existsSync(dir)) return []
  return readdirSync(dir)
    .filter((f) => LICENSE_FILE.test(f))
    .sort()
    .map((f) => ({ file: f, text: readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n').trim() }))
}

// ---- Rust: normal (runtime) dependencies of the shipped binaries -------------------------------------------------
const meta = JSON.parse(execFileSync('cargo', ['metadata', '--format-version', '1', '--locked'], { cwd: repo, maxBuffer: 256 * 1024 * 1024, encoding: 'utf8' }))
const pkgs = new Map(meta.packages.map((p) => [p.id, p]))
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]))
const roots = meta.packages.filter((p) => ['nexus-desktop', 'nexus-cli'].includes(p.name)).map((p) => p.id)
const seen = new Set()
const stack = [...roots]
while (stack.length) {
  const id = stack.pop()
  if (seen.has(id)) continue
  seen.add(id)
  for (const d of nodes.get(id)?.deps ?? []) {
    // Only runtime edges: build scripts' and tests' dependencies are not distributed.
    if (d.dep_kinds.some((k) => k.kind === null)) stack.push(d.pkg)
  }
}
const workspace = new Set(meta.workspace_members)
for (const id of seen) {
  if (workspace.has(id)) continue
  const p = pkgs.get(id)
  components.push({ ecosystem: 'Rust', name: p.name, version: p.version, license: p.license ?? (p.license_file ? 'see file' : 'unknown'), repository: p.repository ?? '', texts: licenceTexts(dirname(p.manifest_path)) })
}

// ---- npm: production dependencies bundled into the frontend --------------------------------------------------------
const app = join(repo, 'apps', 'desktop')
const npmSeen = new Set()
const npmStack = Object.keys(JSON.parse(readFileSync(join(app, 'package.json'), 'utf8')).dependencies ?? {})
while (npmStack.length) {
  const name = npmStack.pop()
  if (npmSeen.has(name)) continue
  const dir = join(app, 'node_modules', name)
  const pj = join(dir, 'package.json')
  if (!existsSync(pj)) continue
  npmSeen.add(name)
  const p = JSON.parse(readFileSync(pj, 'utf8'))
  const repoUrl = typeof p.repository === 'string' ? p.repository : (p.repository?.url ?? '')
  components.push({ ecosystem: 'npm', name, version: p.version, license: typeof p.license === 'string' ? p.license : (p.license?.type ?? 'unknown'), repository: repoUrl, texts: licenceTexts(dir) })
  npmStack.push(...Object.keys(p.dependencies ?? {}))
}

// ---- Output: a summary table, then each distinct licence text once (with the components that carry it) ------------
components.sort((a, b) => a.ecosystem.localeCompare(b.ecosystem) || a.name.localeCompare(b.name) || a.version.localeCompare(b.version))
const byText = new Map() // hash → { text, owners: [] }
for (const c of components) {
  for (const t of c.texts) {
    const h = createHash('sha256').update(t.text).digest('hex')
    if (!byText.has(h)) byText.set(h, { file: t.file, text: t.text, owners: [] })
    byText.get(h).owners.push(`${c.name} ${c.version}`)
  }
}
const counts = {}
for (const c of components) counts[c.license] = (counts[c.license] ?? 0) + 1
let out = `# Third-party notices\n\nNEXUS includes the following third-party components. Each is used under its own licence, reproduced below.\nGenerated by \`scripts/third-party-notices.mjs\` from \`Cargo.lock\` and \`apps/desktop/package-lock.json\` — runtime\ndependencies only (build tools and test dependencies are not distributed).\n\n`
out += `**${components.length} components** — ${Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([l, n]) => `${l}: ${n}`).join(' · ')}\n\n`
out += '| Component | Version | Licence | Source |\n| --- | --- | --- | --- |\n'
for (const c of components) out += `| ${c.ecosystem === 'npm' ? 'npm: ' : ''}${c.name} | ${c.version} | ${c.license.replace(/\|/g, '/')} | ${c.repository.replace(/^git\+/, '').replace(/\.git$/, '')} |\n`
out += '\n## Licence texts\n'
for (const { file, text, owners } of byText.values()) {
  out += `\n### ${file} — ${owners.length > 6 ? `${owners.slice(0, 6).join(', ')} and ${owners.length - 6} more` : owners.join(', ')}\n\n\`\`\`text\n${text.replace(/```/g, "'''")}\n\`\`\`\n`
}
const missing = components.filter((c) => !c.texts.length)
if (missing.length) {
  out += `\n## Components without a licence file in their package\n\nTheir licence is the SPDX expression in the table above (standard text: https://spdx.org/licenses/).\n\n${missing.map((c) => `- ${c.name} ${c.version} — ${c.license}`).join('\n')}\n`
}
writeFileSync(join(repo, 'THIRD_PARTY_NOTICES.md'), out)
console.log(`third-party-notices: ${components.length} components, ${byText.size} distinct licence texts, ${missing.length} without a file`)
