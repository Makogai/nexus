//! Portable project context (Portable Workspace P4): `project-context/<slug>/` in the workspace repository holds what
//! should travel with a project but does not belong in its own repository — a portable project record, an overview,
//! an architecture summary, the current development state, and the project's tasks, decisions, memory, specs and
//! constitutions (written there from schema 2 on).
//!
//! Everything generated here is **deterministic** and cites its source (manifest files, the README, Git): nothing is
//! invented. Overview and architecture are created once and then belong to the person (never overwritten); the
//! architecture summary is left for a reviewed draft. `project.json` and `current-state.md` are regenerated by NEXUS.
//! Repository files are untrusted data: read with size caps, quoted as data, never executed.

use std::path::{Path, PathBuf};

use rusqlite::Connection;
use serde::Serialize;

use crate::error::{CoreError, Result};
use crate::knowledge::frontmatter::Value;
use crate::knowledge::{self, Doc, Kind, Privacy};
use crate::workspace::{self, Workspace};

pub const CONTEXT_DIR: &str = "project-context";
pub const PROJECT_FILE: &str = "project.json";
const MAX_README_EXCERPT: usize = 700;

/// Folder of a kind of project document inside the project's context folder.
pub fn kind_folder(kind: Kind) -> &'static str {
    match kind {
        Kind::Task => "tasks",
        Kind::Decision => "decisions",
        Kind::Note => "memory",
        Kind::Spec => "specs",
        Kind::Rule => "constitutions",
        Kind::Workflow => "workflows",
    }
}

/// A folder-name slug: lowercase letters, digits and `-`, at most 48 characters.
pub fn slug(name: &str) -> String {
    let mut s = String::new();
    for c in name.trim().to_lowercase().chars() {
        if c.is_ascii_alphanumeric() {
            s.push(c);
        } else if !s.ends_with('-') && !s.is_empty() {
            s.push('-');
        }
        if s.len() >= 48 {
            break;
        }
    }
    let s = s.trim_matches('-').to_string();
    if s.is_empty() { "project".into() } else { s }
}

/// The project's context folder (workspace-relative), when the workspace records one.
pub fn context_rel(ws_root: &Path, project_id: &str) -> Option<String> {
    let m = workspace::read_manifest(ws_root).ok()?;
    if m.schema_version < 2 {
        return None;
    }
    m.projects.iter().find(|p| p.id == project_id)?.context.clone().filter(|c| crate::paths::resolve_within(ws_root, c).is_ok())
}

/// Where a new shared document of `kind` for `project_id` goes (relative), if the project has a context folder.
pub fn doc_folder(ws_root: &Path, project_id: &str, kind: Kind) -> Option<String> {
    if kind == Kind::Workflow {
        return None; // workflows stay in the workspace library
    }
    context_rel(ws_root, project_id).map(|c| format!("{c}/{}", kind_folder(kind)))
}

/// The portable project record (`project.json`): what another computer needs to know about the project before it is
/// cloned. Machine-local paths never appear here.
#[derive(Debug, Clone, Serialize, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct ProjectRecord {
    pub nexus: u32,
    pub id: String,
    pub name: String,
    pub remote_url: Option<String>,
    pub stacks: Vec<String>,
    pub package_managers: Vec<String>,
    /// Commands found in the project's manifests (shown, never run); the manifest file stays authoritative.
    pub commands: Vec<CommandRef>,
    pub default_branch: Option<String>,
}

#[derive(Debug, Clone, Serialize, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct CommandRef {
    pub kind: String,
    pub command: String,
    pub source: String,
}

#[derive(Debug, Clone, Serialize, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct Initialized {
    /// Workspace-relative context folder.
    pub dir: String,
    pub created: Vec<String>,
    pub updated: Vec<String>,
    /// Files that already existed and are the person's (never overwritten).
    pub kept: Vec<String>,
}

fn source_of(kind: &str, stacks: &[String]) -> String {
    if stacks.iter().any(|s| s == "rust") && kind != "dev" && kind != "start" {
        "Cargo.toml".into()
    } else {
        "package.json scripts".into()
    }
}

fn record(p: &crate::project::Project) -> ProjectRecord {
    let st = &p.stack;
    ProjectRecord {
        nexus: 1,
        id: p.id.clone(),
        name: p.name.clone(),
        remote_url: p.remote_url.clone(),
        stacks: st.stacks.clone(),
        package_managers: st.package_managers.clone(),
        commands: st.scripts.iter().map(|s| CommandRef { kind: s.kind.clone(), command: s.command.clone(), source: source_of(&s.kind, &st.stacks) }).collect(),
        default_branch: p.local_path.as_deref().and_then(|d| crate::git::status(d).ok()).and_then(|g| g.branch),
    }
}

/// First prose paragraph of the README (headings, badges, HTML and code skipped), capped.
fn readme_excerpt(root: &Path) -> Option<(String, String)> {
    for name in ["README.md", "readme.md", "README"] {
        let path = root.join(name);
        let Ok(meta) = std::fs::metadata(&path) else { continue };
        if meta.len() > 512 * 1024 {
            continue;
        }
        let text = std::fs::read_to_string(&path).ok()?;
        let mut para = String::new();
        let mut in_code = false;
        for line in text.lines() {
            let t = line.trim();
            if t.starts_with("```") {
                in_code = !in_code;
                continue;
            }
            if in_code || t.starts_with('#') || t.starts_with('<') || t.starts_with("[![") || t.starts_with("![") {
                if !para.is_empty() && !in_code {
                    break;
                }
                continue;
            }
            if t.is_empty() {
                if !para.is_empty() {
                    break;
                }
                continue;
            }
            if !para.is_empty() {
                para.push(' ');
            }
            para.push_str(t);
        }
        let para: String = para.chars().filter(|c| !c.is_control()).collect();
        if para.is_empty() {
            return None;
        }
        let clipped = if para.chars().count() > MAX_README_EXCERPT { format!("{}…", para.chars().take(MAX_README_EXCERPT).collect::<String>()) } else { para };
        return Some((name.to_string(), clipped));
    }
    None
}

/// Top-level folders with entry counts (skipping hidden, dependency and build folders) and conventional entry points.
fn layout(root: &Path) -> (Vec<(String, usize)>, Vec<String>) {
    const SKIP: &[&str] = &["node_modules", "target", "dist", "build", "vendor", "out", "coverage", "__pycache__", "bin", "obj"];
    let mut dirs: Vec<(String, usize)> = std::fs::read_dir(root)
        .into_iter()
        .flatten()
        .flatten()
        .filter(|e| e.file_type().is_ok_and(|t| t.is_dir()))
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .filter(|n| !n.starts_with('.') && !SKIP.contains(&n.as_str()))
        .map(|n| {
            let count = std::fs::read_dir(root.join(&n)).map(|rd| rd.take(10_000).count()).unwrap_or(0);
            (n, count)
        })
        .collect();
    dirs.sort();
    dirs.truncate(30);
    const ENTRIES: &[&str] = &[
        "src/main.rs", "src/lib.rs", "src/main.ts", "src/main.js", "src/index.ts", "src/index.js", "src/main.tsx", "src/App.vue", "src/app/app.config.ts",
        "index.html", "main.py", "app.py", "manage.py", "app/main.py", "artisan", "public/index.php", "lib/main.dart", "cmd", "main.go",
    ];
    let entries = ENTRIES.iter().filter(|e| root.join(e).exists()).map(|e| e.to_string()).collect();
    (dirs, entries)
}

fn doc(kind: Kind, title: &str, project_id: &str, topic: &str, status: &str, body: String) -> Doc {
    let now = knowledge::timestamp(crate::now_ms());
    let mut fm = knowledge::frontmatter::Frontmatter::default();
    fm.set("nexus", Value::Int(knowledge::SCHEMA));
    fm.set("id", Value::Str(uuid::Uuid::now_v7().to_string()));
    fm.set("kind", Value::Str(kind.as_str().into()));
    fm.set("title", Value::Str(title.chars().take(knowledge::MAX_TITLE_CHARS).collect()));
    fm.set("status", Value::Str(status.into()));
    fm.set("project", Value::Str(project_id.into()));
    fm.set("topic", Value::Str(topic.into()));
    fm.set("created", Value::Str(now.clone()));
    fm.set("updated", Value::Str(now));
    fm.set("source", Value::Str("import".into()));
    Doc { fm, body }
}

fn overview_body(p: &crate::project::Project, root: Option<&Path>) -> String {
    let mut b = String::from("_Created by NEXUS from the project's files; every fact names its source. This document is yours — NEXUS will not overwrite it._\n\n## What it is\n\n");
    match root.and_then(readme_excerpt) {
        Some((file, text)) => b.push_str(&format!("> {}\n\n_Source: {file}._\n\n", text.replace('\n', " "))),
        None => b.push_str("_Not documented yet._ Describe the project's purpose, its users and what \"done\" means here.\n\n"),
    }
    b.push_str("## Repository\n\n");
    b.push_str(&format!("- Remote: {}\n", p.remote_url.as_deref().map(|r| format!("`{r}`")).unwrap_or_else(|| "none recorded".into())));
    b.push_str("\n## Technology (detected from manifest files)\n\n");
    if p.stack.stacks.is_empty() {
        b.push_str("- Nothing detected.\n");
    } else {
        b.push_str(&format!("- Stacks: {}\n", p.stack.stacks.join(", ")));
    }
    if !p.stack.package_managers.is_empty() {
        b.push_str(&format!("- Package managers: {}\n", p.stack.package_managers.join(", ")));
    }
    if !p.stack.scripts.is_empty() {
        b.push_str("\n## Commands (from the project's manifests — the manifests stay authoritative; NEXUS never runs them on its own)\n\n");
        for s in &p.stack.scripts {
            b.push_str(&format!("- {}: `{}`\n", s.kind, s.command));
        }
    }
    let docs: Vec<&str> = [("README", p.stack.has_readme), ("CLAUDE.md", p.stack.has_claude_md), ("AGENTS.md", p.stack.has_agents_md), (".claude/", p.stack.has_claude_dir)]
        .iter()
        .filter(|(_, has)| *has)
        .map(|(n, _)| *n)
        .collect();
    if !docs.is_empty() {
        b.push_str(&format!("\n## Instructions and documentation in the repository\n\n- {}\n", docs.join(", ")));
    }
    b
}

fn architecture_body(root: Option<&Path>) -> String {
    let mut b = String::from("_Created by NEXUS. The structure below is read from the repository; the summary is left for you or a reviewed draft._\n\n## Structure (verified from the file system)\n\n");
    match root {
        Some(r) => {
            let (dirs, entries) = layout(r);
            if dirs.is_empty() {
                b.push_str("- No source folders at the top level.\n");
            }
            for (d, n) in &dirs {
                b.push_str(&format!("- `{d}/` — {n} entr{}\n", if *n == 1 { "y" } else { "ies" }));
            }
            if !entries.is_empty() {
                b.push_str(&format!("\nConventional entry points present: {}.\n", entries.iter().map(|e| format!("`{e}`")).collect::<Vec<_>>().join(", ")));
            }
        }
        None => b.push_str("- The project is not on this computer; clone it and refresh the context.\n"),
    }
    b.push_str("\n## Architecture summary\n\n_Not written yet._ Ask Claude in a session to draft it from the code (skill `workspace:architecture-documentation`); a draft states which parts are inferred and stays `status: draft` until you review it.\n");
    b
}

/// The generated current development state (verified Git facts and NEXUS records; regenerated, never edited).
pub fn current_state_body(conn: &Connection, p: &crate::project::Project, ws_id: &str) -> String {
    let mut b = String::from("_Generated by NEXUS from verified sources; regenerated at meaningful points (project setup, end of a development session). Write lasting notes in `decisions/` or `memory/` instead._\n\n## Repository (verified)\n\n");
    match p.local_path.as_deref().filter(|d| d.is_dir()).and_then(|d| crate::git::status(d).ok()).filter(|g| g.is_repo) {
        Some(g) => {
            b.push_str(&format!("- Branch: {}\n", g.branch.as_deref().map(|x| format!("`{x}`")).unwrap_or_else(|| "detached".into())));
            if let Some(c) = &g.last_commit {
                b.push_str(&format!("- Last commit: `{}` {} ({})\n", &c.oid[..c.oid.len().min(10)], crate::knowledge::tasks::escape_untrusted(&c.summary, 120), knowledge::timestamp(c.timestamp_ms)));
            }
            let changed = g.staged + g.unstaged + g.untracked;
            b.push_str(&format!("- Uncommitted changes: {changed} file(s) on the computer that generated this\n"));
        }
        None => b.push_str("- The project is not on the computer that generated this.\n"),
    }
    let open: Vec<(String, String)> = conn
        .prepare("SELECT title, COALESCE(status, '') FROM knowledge_items WHERE workspace_id = ?1 AND project_id = ?2 AND kind = 'task' AND valid = 1 AND COALESCE(status, '') NOT IN ('done') ORDER BY CASE status WHEN 'in-progress' THEN 0 WHEN 'blocked' THEN 1 WHEN 'review' THEN 2 ELSE 3 END, updated DESC LIMIT 8")
        .and_then(|mut s| s.query_map([ws_id, p.id.as_str()], |r| Ok((r.get(0)?, r.get(1)?))).and_then(|rows| rows.collect()))
        .unwrap_or_default();
    b.push_str("\n## Work (from the workspace's task records)\n\n");
    if open.is_empty() {
        b.push_str("- No open tasks.\n");
    }
    for (t, s) in &open {
        b.push_str(&format!("- [{s}] {}\n", crate::knowledge::tasks::escape_untrusted(t, 120)));
    }
    b
}

fn write_doc(path: &Path, d: &Doc) -> Result<()> {
    d.validate(Privacy::Shared).map_err(CoreError::Invalid)?;
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir).map_err(|e| CoreError::io("cannot create", dir, e))?;
    }
    workspace::write_atomic(path, d.render().as_bytes())
}

/// Create the project's context folder (or fill in what is missing) and regenerate the generated files.
pub fn init(conn: &Connection, data_dir: &Path, ws: &Workspace, project_id: &str) -> Result<Initialized> {
    let root = &ws.root_path;
    workspace::ensure_writable(root)?;
    let mut m = workspace::read_manifest(root)?;
    if m.schema_version < 2 {
        return Err(CoreError::invalid("project context needs workspace schema 2 — migrate the workspace first"));
    }
    let p = crate::project::get(conn, project_id)?;
    if p.workspace_id != ws.id {
        return Err(CoreError::invalid("the project is not part of this workspace"));
    }
    let entry_index = m.projects.iter().position(|x| x.id == project_id).ok_or_else(|| CoreError::not_found("the project is not in the workspace manifest"))?;
    let rel = match m.projects[entry_index].context.clone().filter(|c| crate::paths::resolve_within(root, c).is_ok()) {
        Some(c) => c,
        None => {
            let taken: Vec<String> = m.projects.iter().filter_map(|x| x.context.clone()).collect();
            let base = slug(&p.name);
            let mut candidate = format!("{CONTEXT_DIR}/{base}");
            let mut n = 2;
            while taken.contains(&candidate) || (root.join(&candidate).exists() && !root.join(&candidate).join(PROJECT_FILE).is_file()) {
                candidate = format!("{CONTEXT_DIR}/{base}-{n}");
                n += 1;
            }
            m.projects[entry_index].context = Some(candidate.clone());
            if !m.has_feature("project-context") {
                m.features.push("project-context".into());
            }
            workspace::write_manifest(root, &m)?;
            candidate
        }
    };
    let dir = crate::paths::resolve_within(root, &rel)?;
    std::fs::create_dir_all(&dir).map_err(|e| CoreError::io("cannot create", &dir, e))?;
    let local = p.local_path.as_deref().filter(|d| d.is_dir());
    let mut out = Initialized { dir: rel.clone(), created: vec![], updated: vec![], kept: vec![] };

    // project.json — regenerated when it changed.
    let rec = serde_json::to_string_pretty(&record(&p)).map_err(|source| CoreError::Json { what: PROJECT_FILE.into(), source })? + "\n";
    let rec_path = dir.join(PROJECT_FILE);
    match std::fs::read_to_string(&rec_path) {
        Ok(old) if old == rec => out.kept.push(format!("{rel}/{PROJECT_FILE}")),
        Ok(_) => {
            workspace::write_atomic(&rec_path, rec.as_bytes())?;
            out.updated.push(format!("{rel}/{PROJECT_FILE}"));
        }
        Err(_) => {
            workspace::write_atomic(&rec_path, rec.as_bytes())?;
            out.created.push(format!("{rel}/{PROJECT_FILE}"));
        }
    }
    // overview.md / architecture.md — created once, then the person's.
    for (file, title, topic, body) in [
        ("overview.md", format!("{} — overview", p.name), "overview", overview_body(&p, local)),
        ("architecture.md", format!("{} — architecture", p.name), "architecture", architecture_body(local)),
    ] {
        let path = dir.join(file);
        if path.exists() {
            out.kept.push(format!("{rel}/{file}"));
            continue;
        }
        let status = if topic == "architecture" { "draft" } else { "active" };
        let d = doc(Kind::Spec, &title, &p.id, topic, status, body);
        match write_doc(&path, &d) {
            Ok(()) => out.created.push(format!("{rel}/{file}")),
            // Repository text that cannot live in portable knowledge (e.g. credential-shaped) is left out, not copied.
            Err(_) => {
                write_doc(&path, &doc(Kind::Spec, &title, &p.id, topic, status, "_Created by NEXUS. The repository's own text could not be copied safely; describe the project here._\n".into()))?;
                out.created.push(format!("{rel}/{file}"));
            }
        }
    }
    write_current_state(conn, ws, &p, &dir, &rel, &mut out)?;
    knowledge::service::refresh(conn, data_dir, ws)?;
    Ok(out)
}

fn write_current_state(conn: &Connection, ws: &Workspace, p: &crate::project::Project, dir: &Path, rel: &str, out: &mut Initialized) -> Result<()> {
    let path = dir.join("current-state.md");
    let body = current_state_body(conn, p, &ws.id);
    let existing = std::fs::read_to_string(&path).ok().and_then(|t| Doc::parse(&t).ok());
    if let Some(mut d) = existing {
        if d.body.trim() == body.trim() {
            out.kept.push(format!("{rel}/current-state.md"));
            return Ok(());
        }
        d.body = body;
        d.fm.set("updated", Value::Str(knowledge::timestamp(crate::now_ms())));
        write_doc(&path, &d)?;
        out.updated.push(format!("{rel}/current-state.md"));
    } else {
        write_doc(&path, &doc(Kind::Spec, &format!("{} — current state", p.name), &p.id, "current-state", "active", body))?;
        out.created.push(format!("{rel}/current-state.md"));
    }
    Ok(())
}

/// Regenerate `current-state.md` (and `project.json`) for a project with a context folder; a no-op otherwise.
pub fn refresh_state(conn: &Connection, data_dir: &Path, ws: &Workspace, project_id: &str) -> Result<Option<Initialized>> {
    if context_rel(&ws.root_path, project_id).is_none() || !workspace::compat(&workspace::read_manifest(&ws.root_path)?).writable {
        return Ok(None);
    }
    init(conn, data_dir, ws, project_id).map(Some)
}

/// Absolute context folder of a project, if it has one.
pub fn context_dir(ws: &Workspace, project_id: &str) -> Option<PathBuf> {
    context_rel(&ws.root_path, project_id).and_then(|r| crate::paths::resolve_within(&ws.root_path, &r).ok())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn slugs_are_safe_folder_names() {
        assert_eq!(slug("My Shop (v2)"), "my-shop-v2");
        assert_eq!(slug("../../etc"), "etc");
        assert_eq!(slug("!!!"), "project");
        assert!(slug(&"x".repeat(100)).len() <= 48);
    }

    #[test]
    fn readme_excerpts_skip_headings_badges_and_code() {
        let t = tempfile::tempdir().unwrap();
        std::fs::write(t.path().join("README.md"), "# Shop\n[![ci](x)](y)\n\n```sh\nnpm i\n```\n\nA small shop for\nhand-made things.\n\n## Setup\n").unwrap();
        assert_eq!(readme_excerpt(t.path()).unwrap().1, "A small shop for hand-made things.");
    }
}
